  _keyExpansion(key) {
    const w = Array.from(key);
    for (let i = 4; i < 44; i++) {
      let temp = w.slice((i - 1) * 4, i * 4);
      if (i % 4 === 0) {
        temp = [this.sbox[temp[1]], this.sbox[temp[2]], this.sbox[temp[3]], this.sbox[temp[0]]];
        temp[0] ^= this.rcon[Math.floor(i / 4)];
      }
      for (let j = 0; j < 4; j++) {
        w.push(w[(i - 4) * 4 + j] ^ temp[j]);
      }
    }
    return w;
  }

  _xtime(x) {
    return (x & 0x80) ? ((x << 1) ^ 0x1b) & 0xff : (x << 1) & 0xff;
  }

  encrypt(plaintext) {
    if (plaintext.length !== 16) throw new Error("Plaintext must be 16 bytes");
    let state = Array.from({ length: 4 }, () => new Array(4));

    for (let c = 0; c < 4; c++) {
      for (let r = 0; r < 4; r++) {
        state[r][c] = plaintext[c * 4 + r];
      }
    }

    // AddRoundKey Round 0
    for (let r = 0; r < 4; r++) {
      for (let c = 0; c < 4; c++) {
        state[r][c] ^= this.roundKeys[c * 4 + r];
      }
    }

    for (let round = 1; round <= 9; round++) {
      // SubBytes
      for (let r = 0; r < 4; r++) {
        for (let c = 0; c < 4; c++) {
          state[r][c] = this.sbox[state[r][c]];
        }
      }

      // ShiftRows
      const s1 = state[1][0], s20 = state[2][0], s21 = state[2][1], s30 = state[3][0], s31 = state[3][1], s32 = state[3][2];
      state[1][0] = state[1][1]; state[1][1] = state[1][2]; state[1][2] = state[1][3]; state[1][3] = s1;
      state[2][0] = state[2][2]; state[2][1] = state[2][3]; state[2][2] = s20; state[2][3] = s21;
      state[3][0] = state[3][3]; state[3][1] = s30; state[3][2] = s31; state[3][3] = s32;

      // MixColumns
      for (let c = 0; c < 4; c++) {
        const a0 = state[0][c], a1 = state[1][c], a2 = state[2][c], a3 = state[3][c];
        state[0][c] = this._xtime(a0 ^ a1) ^ a1 ^ a2 ^ a3;
        state[1][c] = this._xtime(a1 ^ a2) ^ a0 ^ a2 ^ a3;
        state[2][c] = this._xtime(a2 ^ a3) ^ a0 ^ a1 ^ a3;
        state[3][c] = this._xtime(a3 ^ a0) ^ a0 ^ a1 ^ a2;
      }

      // AddRoundKey
      const offset = round * 16;
      for (let r = 0; r < 4; r++) {
        for (let c = 0; c < 4; c++) {
          state[r][c] ^= this.roundKeys[offset + c * 4 + r];
        }
      }
    }

    // Final Round
    for (let r = 0; r < 4; r++) {
      for (let c = 0; c < 4; c++) {
        state[r][c] = this.sbox[state[r][c]];
      }
    }
    const s1 = state[1][0], s20 = state[2][0], s21 = state[2][1], s30 = state[3][0], s31 = state[3][1], s32 = state[3][2];
    state[1][0] = state[1][1]; state[1][1] = state[1][2]; state[1][2] = state[1][3]; state[1][3] = s1;
    state[2][0] = state[2][2]; state[2][1] = state[2][3]; state[2][2] = s20; state[2][3] = s21;
    state[3][0] = state[3][3]; state[3][1] = s30; state[3][2] = s31; state[3][3] = s32;

    const offset = 160;
    for (let r = 0; r < 4; r++) {
      for (let c = 0; c < 4; c++) {
        state[r][c] ^= this.roundKeys[offset + c * 4 + r];
      }
    }

    const out = [];
    for (let c = 0; c < 4; c++) {
      for (let r = 0; r < 4; r++) {
        out.push(state[r][c]);
      }
    }
    return out;
  }
